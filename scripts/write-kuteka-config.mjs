#!/usr/bin/env node
/**
 * Writes apps/web/public/kuteka-config.js (and optional out/prebuilt copies)
 * from NEXT_PUBLIC_SUPABASE_* env. Safe to run with empty values.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const url = process.env.NEXT_PUBLIC_SUPABASE_URL ?? '';
const anon = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ?? '';

const body = `/* Generated by scripts/write-kuteka-config.mjs — do not commit secrets in git if real. */
window.__KUTEKA_CONFIG__ = {
  supabaseUrl: ${JSON.stringify(url)},
  supabaseAnonKey: ${JSON.stringify(anon)},
};
`;

const targets = [
  path.join(root, 'apps/web/public/kuteka-config.js'),
  path.join(root, 'apps/web/out/kuteka-config.js'),
  path.join(root, 'prebuilt/web-out/kuteka-config.js'),
  path.join(root, 'dist/kuteka-config.js'),
].filter((p, i) => i === 0 || fs.existsSync(path.dirname(p)));

for (const target of targets) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, body, 'utf8');
  console.log(`Wrote ${path.relative(root, target)} (url=${url ? 'set' : 'empty'})`);
}
