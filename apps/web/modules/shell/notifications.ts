export function notificationsForMode(
  mode: ExperienceMode,
  locale: AppLocale = 'pt',
): ShellNotification[] {
  return CATALOG[locale][mode] ?? CATALOG.pt[mode] ?? [];
}

export function unreadCount(items: readonly ShellNotification[]): number {
  return items.filter((item) => item.unread !== false).length;
}
